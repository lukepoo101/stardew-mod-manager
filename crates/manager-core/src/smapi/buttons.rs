/// Whether text is a SMAPI key binding: button names joined by `+` (held
/// together) and `,` (alternatives), such as "LeftShift + F3" or
/// "F3, LeftShoulder". Every part must be a button name.
pub fn is_keybind(text: &str) -> bool {
    let mut parts = text
        .split([',', '+'])
        .map(str::trim)
        .filter(|part| !part.is_empty())
        .peekable();
    parts.peek().is_some()
        && parts.all(|part| SMAPI_BUTTONS.iter().any(|b| b.eq_ignore_ascii_case(part)))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Shared word for word with `buttons.test.ts`: (text, is a key binding).
    pub(crate) const KEYBIND_CASES: &[(&str, bool)] = &[
        ("F3", true),
        ("RightThumbstickRight", true),
        ("F3,LeftShoulder", true),
        ("LeftShift + F3", true),
        ("LeftShift+F3", true),
        ("DPadRight, RightShoulder", true),
        ("LaunchApplication1", true),
        ("f9", true),
        ("", false),
        ("F25", false),
        ("Bearer abc123def456", false),
        ("correcthorsebattery", false),
        ("abcdefghijklmnop", false),
        ("wJalrXUtnFEMI/K7MDENG+bPxRfiCYEXAMPLEKEY", false),
        ("123456789012", false),
    ];

    #[test]
    fn key_bindings_are_told_from_credentials() {
        for (text, expected) in KEYBIND_CASES {
            assert_eq!(is_keybind(text), *expected, "{text}");
        }
    }
}

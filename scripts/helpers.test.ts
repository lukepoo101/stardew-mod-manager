// Tests for the Bun helper scripts. Run with `bun test ./scripts`.
//
// Each test copies a script into a throwaway root whose path contains a space
// and runs it with this Bun, so path handling and quoting are exercised on
// every platform the test runs on.
import { afterEach, describe, expect, test } from "bun:test";
import {
  chmodSync,
  mkdirSync,
  mkdtempSync,
  rmSync,
  symlinkSync,
} from "node:fs";
import { EOL, tmpdir } from "node:os";
import path from "node:path";

const REPO = path.resolve(import.meta.dir, "..");
const roots: string[] = [];

function makeRoot(label: string): string {
  const root = path.join(mkdtempSync(path.join(tmpdir(), "s5-")), label);
  mkdirSync(path.join(root, "scripts"), { recursive: true });
  roots.push(path.dirname(root));
  return root;
}

afterEach(() => {
  for (const dir of roots.splice(0)) {
    rmSync(dir, { recursive: true, force: true });
  }
});

async function write(file: string, content: string | Blob) {
  await Bun.write(file, content);
}

function run(cmd: string[], cwd: string, env?: Record<string, string>) {
  const result = Bun.spawnSync(cmd, {
    cwd,
    env: { ...process.env, ...env },
    stdout: "pipe",
    stderr: "pipe",
  });
  return {
    exitCode: result.exitCode,
    stdout: result.stdout.toString(),
    stderr: result.stderr.toString(),
  };
}

describe("read-rust-toolchain", () => {
  async function readToolchain(manifest: string | null) {
    const root = makeRoot("toolchain root");
    await write(
      path.join(root, "scripts", "read-rust-toolchain.ts"),
      Bun.file(path.join(REPO, "scripts", "read-rust-toolchain.ts")),
    );
    if (manifest !== null) {
      await write(path.join(root, "rust-toolchain.toml"), manifest);
    }
    return run(
      [process.execPath, path.join(root, "scripts", "read-rust-toolchain.ts")],
      root,
    );
  }

  test("prints the repository's channel as a step output", async () => {
    const manifest = await Bun.file(
      path.join(REPO, "rust-toolchain.toml"),
    ).text();
    const channel = (Bun.TOML.parse(manifest) as any).toolchain.channel;
    const result = run(
      [process.execPath, path.join(REPO, "scripts", "read-rust-toolchain.ts")],
      REPO,
    );
    expect(result).toEqual({
      exitCode: 0,
      stdout: `toolchain=${channel}${EOL}`,
      stderr: "",
    });
  });

  test.each([
    ["LF", '[toolchain]\nchannel = "1.99.1"\nprofile = "minimal"\n'],
    ["CRLF", '[toolchain]\r\nchannel = "1.99.1"\r\n'],
    ["literal string", "[toolchain]\nchannel = '1.99.1'\n"],
    ["trimmed multi-line string", '[toolchain]\nchannel = """\n1.99.1"""\n'],
  ])("accepts a %s manifest", async (_, manifest) => {
    expect(await readToolchain(manifest)).toEqual({
      exitCode: 0,
      stdout: `toolchain=1.99.1${EOL}`,
      stderr: "",
    });
  });

  test.each([
    ["an escaped LF", '[toolchain]\nchannel = "1.99\\n.1"\n'],
    ["an escaped CR", '[toolchain]\nchannel = "1.99.1\\r"\n'],
    ["a multi-line channel", '[toolchain]\nchannel = """1.99\n.1"""\n'],
    ["an empty channel", '[toolchain]\nchannel = ""\n'],
    ["an integer channel", "[toolchain]\nchannel = 199\n"],
    ["an array channel", '[toolchain]\nchannel = ["1.99.1"]\n'],
    ["no channel", '[toolchain]\nprofile = "minimal"\n'],
    ["no toolchain table", 'channel = "1.99.1"\n'],
    ["a string toolchain", 'toolchain = "1.99.1"\n'],
  ])("rejects %s", async (_, manifest) => {
    const result = await readToolchain(manifest);
    expect(result.exitCode).toBe(1);
    expect(result.stdout).toBe("");
    // Only stdout's line ending is part of the contract.
    expect(result.stderr.trimEnd()).toBe(
      "rust-toolchain.toml must contain a single toolchain channel",
    );
  });

  test.each([
    ["invalid TOML", '[toolchain\nchannel = "1.99.1"\n'],
    ["a duplicate key", '[toolchain]\nchannel = "1.99.1"\nchannel = "1"\n'],
    ["a missing manifest", null],
  ])("fails on %s", async (_, manifest) => {
    const result = await readToolchain(manifest);
    expect(result.exitCode).toBe(1);
    expect(result.stdout).toBe("");
    expect(result.stderr).toContain("rust-toolchain.toml");
  });
});

describe("check-generated-bindings", () => {
  const OUT_OF_DATE =
    "Generated DTOs are out of date. Run `cargo test -p manager-app`, " +
    "then `bun run bindings:check` and commit the result.";
  const SOURCE = ["crates", "manager-app", "bindings"];
  const DESTINATION = ["apps", "desktop", "src", "shared", "api", "generated"];

  // A ts-rs style export: one line, commas, no semicolons. Biome reformats it.
  const dto = (name: string, field = "id: string") =>
    `// This file was generated by [ts-rs](https://github.com/Aleph-Alpha/ts-rs). Do not edit this file manually.\n\nexport type ${name} = { ${field}, };\n`;

  // An isolated git home, so the user's global config (pager, autocrlf,
  // hooks, signing) cannot change the result.
  function gitEnv(root: string): Record<string, string> {
    const home = path.join(path.dirname(root), "home");
    mkdirSync(home, { recursive: true });
    return {
      GIT_CONFIG_GLOBAL: path.join(home, "gitconfig"),
      GIT_CONFIG_NOSYSTEM: "1",
      GIT_AUTHOR_NAME: "S5",
      GIT_AUTHOR_EMAIL: "s5@example.invalid",
      GIT_COMMITTER_NAME: "S5",
      GIT_COMMITTER_EMAIL: "s5@example.invalid",
    };
  }

  function git(root: string, ...args: string[]) {
    const result = run(["git", ...args], root, gitEnv(root));
    if (result.exitCode !== 0) {
      throw new Error(`git ${args.join(" ")} failed: ${result.stderr}`);
    }
    return result.stdout;
  }

  function check(root: string, env: Record<string, string> = {}) {
    return run(
      [
        process.execPath,
        path.join(root, "scripts", "check-generated-bindings.ts"),
      ],
      root,
      { ...gitEnv(root), ...env },
    );
  }

  const source = (root: string, name: string) =>
    path.join(root, ...SOURCE, name);
  const destination = (root: string, name: string) =>
    path.join(root, ...DESTINATION, name);

  // A committed repository whose destination is in sync with its source:
  // two DTOs plus the hand-written index.ts. The real node_modules folders
  // are linked in, so the pinned Biome and biome.json are used.
  async function makeRepo({ withBiome = true } = {}) {
    const root = makeRoot("bindings repo");
    await write(
      path.join(root, "scripts", "check-generated-bindings.ts"),
      Bun.file(path.join(REPO, "scripts", "check-generated-bindings.ts")),
    );
    await write(
      path.join(root, "biome.json"),
      Bun.file(path.join(REPO, "biome.json")),
    );
    await write(path.join(root, ".gitignore"), "node_modules\n");
    if (withBiome) {
      mkdirSync(path.join(root, "apps", "desktop"), { recursive: true });
      symlinkSync(
        path.join(REPO, "apps", "desktop", "node_modules"),
        path.join(root, "apps", "desktop", "node_modules"),
        "junction",
      );
      // Bun's isolated install links each package into the root
      // node_modules/.bun store by a relative path. Windows resolves that
      // path from where the link was reached, so the root store has to be
      // linked in too or the pinned Biome looks missing.
      symlinkSync(
        path.join(REPO, "node_modules"),
        path.join(root, "node_modules"),
        "junction",
      );
    }
    await write(source(root, "AlphaDto.ts"), dto("AlphaDto"));
    await write(source(root, "BetaDto.ts"), dto("BetaDto"));
    await write(
      destination(root, "index.ts"),
      'export * from "./AlphaDto";\nexport * from "./BetaDto";\n',
    );
    git(root, "init", "-q");
    git(root, "config", "core.autocrlf", "false");
    if (withBiome) {
      // The first run formats the copies into the destination.
      expect(check(root).exitCode).toBe(1);
    } else {
      await write(destination(root, "AlphaDto.ts"), dto("AlphaDto"));
      await write(destination(root, "BetaDto.ts"), dto("BetaDto"));
    }
    git(root, "add", "-A");
    git(root, "commit", "-q", "-m", "fixture");
    return root;
  }

  test("passes on a tree that is in sync", async () => {
    const root = await makeRepo();
    const formatted = await Bun.file(destination(root, "AlphaDto.ts")).text();
    expect(formatted).toContain("export type AlphaDto = { id: string };");
    const result = check(root);
    expect(result.exitCode).toBe(0);
    expect(result.stderr).toBe("");
    expect(git(root, "status", "--porcelain")).toBe("");
  });

  test("fails when a source binding changed", async () => {
    const root = await makeRepo();
    await write(source(root, "AlphaDto.ts"), dto("AlphaDto", "id: number"));
    const result = check(root);
    expect(result.exitCode).toBe(1);
    expect(result.stderr.trimEnd()).toEndWith(OUT_OF_DATE);
    // git diff prints the drift, as before.
    expect(result.stdout).toContain("-export type AlphaDto = { id: string };");
    expect(result.stdout).toContain("+export type AlphaDto = { id: number };");
  });

  test("fails when a new source binding is not checked in", async () => {
    const root = await makeRepo();
    await write(source(root, "GammaDto.ts"), dto("GammaDto"));
    const result = check(root);
    expect(result.exitCode).toBe(1);
    expect(result.stderr.trimEnd()).toEndWith(OUT_OF_DATE);
    expect(git(root, "status", "--porcelain")).toContain(
      "?? apps/desktop/src/shared/api/generated/GammaDto.ts",
    );
  });

  test("deletes an untracked stale destination file and passes", async () => {
    const root = await makeRepo();
    await write(destination(root, "StaleDto.ts"), dto("StaleDto"));
    const result = check(root);
    expect(result.exitCode).toBe(0);
    expect(await Bun.file(destination(root, "StaleDto.ts")).exists()).toBe(
      false,
    );
  });

  test("fails when a checked-in binding lost its source", async () => {
    const root = await makeRepo();
    rmSync(source(root, "BetaDto.ts"));
    const result = check(root);
    expect(result.exitCode).toBe(1);
    expect(result.stderr.trimEnd()).toEndWith(OUT_OF_DATE);
    expect(await Bun.file(destination(root, "BetaDto.ts")).exists()).toBe(
      false,
    );
    expect(await Bun.file(destination(root, "index.ts")).exists()).toBe(true);
  });

  test("treats a missing source directory as no bindings", async () => {
    const root = await makeRepo();
    rmSync(path.join(root, ...SOURCE), { recursive: true });
    const result = check(root);
    expect(result.exitCode).toBe(1);
    expect(result.stderr.trimEnd()).toEndWith(OUT_OF_DATE);
    expect(await Bun.file(destination(root, "AlphaDto.ts")).exists()).toBe(
      false,
    );
    expect(await Bun.file(destination(root, "index.ts")).exists()).toBe(true);
  });

  test("fails, without downloading or using another Biome, when apps/desktop has none", async () => {
    const root = await makeRepo({ withBiome: false });
    // A decoy `biome` on PATH must not be used.
    const bin = path.join(path.dirname(root), "bin");
    const marker = path.join(path.dirname(root), "decoy-ran");
    await write(
      path.join(bin, "biome"),
      `#!/bin/sh\ntouch "${marker}"\nexit 0\n`,
    );
    await write(
      path.join(bin, "biome.cmd"),
      `@echo off\r\ntype nul > "${marker}"\r\n`,
    );
    chmodSync(path.join(bin, "biome"), 0o755);
    const result = check(root, {
      PATH: `${bin}${path.delimiter}${process.env.PATH}`,
    });
    expect(result.exitCode).toBe(1);
    expect(result.stderr).toContain("Biome is not installed in apps/desktop");
    expect(await Bun.file(marker).exists()).toBe(false);
  });
});

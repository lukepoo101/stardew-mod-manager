const BUTTONS = new Set(SMAPI_BUTTONS.map((b) => b.toLowerCase()));

/**
 * Whether text is a SMAPI key binding: button names joined by `+` (held
 * together) and `,` (alternatives), such as "LeftShift + F3" or
 * "F3, LeftShoulder". Every part must be a button name; SMAPI reads them
 * ignoring case.
 */
export function isKeybind(text: string): boolean {
  const parts = text
    .split(/[,+]/)
    .map((part) => part.trim())
    .filter((part) => part !== "");
  return (
    parts.length > 0 && parts.every((part) => BUTTONS.has(part.toLowerCase()))
  );
}
